import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,readFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomUUID} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {createStudio} from '../server/index.mjs';
import {digest} from '../server/store.mjs';

test('local import validates identity, preserves master, and cannot replay or approve it',async t=>{
 const home=mkdtempSync(join(tmpdir(),'reel-import-'));
 const app=await createStudio({home,runtime:{close:async()=>{}}});
 t.after(async()=>{await app.close();rmSync(home,{recursive:true,force:true});});
 const sourceDir=join(home,'owner-source');mkdirSync(sourceDir);
 const file=join(sourceDir,'owner.mp4');
 const encode=spawnSync(process.env.FFMPEG_BIN||'ffmpeg',['-hide_banner','-loglevel','error','-nostdin','-f','lavfi','-i','color=c=blue:s=1080x1920:r=30:d=1.2','-f','lavfi','-i','anullsrc=r=48000:cl=stereo','-t','1.2','-c:v','libx264','-preset','ultrafast','-pix_fmt','yuv420p','-c:a','aac',file],{timeout:30000});
 assert.equal(encode.status,0);
 const sha256=digest(readFileSync(file));
 const p=app.store.create({requestKey:randomUUID(),title:'Owner film',idea:'Private owner film',templateId:'kinetic',model:'gpt-6.1-sol',effort:'medium',duration:15,language:'en'});
 const args={projectId:p.id,expectedRevision:p.revision,requestKey:randomUUID(),videoPath:file,sourceDir,sha256,metadata:{title:'Owner film',caption:'An existing private film.',hashtags:[],evidence:[]},checks:[]};
 assert.equal((await app.invoke('reel_import',{...args,sha256:'0'.repeat(64)})).isError,true);
 assert.equal((await app.invoke('reel_import',{...args,sourceDir:join(home,'media')})).isError,true);
 assert.equal((await app.invoke('reel_import',{...args,expectedRevision:999})).isError,true);
 assert.equal(app.store.get(p.id).versions.length,0);
 const first=await app.invoke('reel_import',args);assert.notEqual(first.isError,true);
 const v=app.store.get(p.id).versions[0];
 assert.equal(v.origin,'local_import');assert.equal(v.approval,null);assert.equal(app.store.get(p.id).status,'review');
 assert.equal(digest(readFileSync(file)),sha256);assert.equal(digest(readFileSync(v.path)),sha256);
 assert.notEqual(file,v.path);assert.equal(app.store.get(p.id).jobs.length,0);
 const second=await app.invoke('reel_import',args);assert.equal(second.structuredContent.reused,true);assert.equal(app.store.get(p.id).versions.length,1);
 const view=first.structuredContent.snapshot.projects.find(x=>x.id===p.id).versions[0];
 assert.ok(view.previewURL);assert.ok(view.posterURL);assert.equal(view.path,undefined);assert.equal(view.sourceDir,undefined);
 const thumb=await fetch(view.posterURL);assert.equal(thumb.status,200);assert.equal(thumb.headers.get('content-type'),'image/jpeg');assert.ok((await thumb.arrayBuffer()).byteLength>1000);
 const range=await fetch(view.previewURL,{headers:{Range:'bytes=0-99'}});assert.equal(range.status,206);assert.equal((await range.arrayBuffer()).byteLength,100);
 assert.equal((await fetch(app.address+'/media/poster-'+randomUUID()+new URL(view.posterURL).search)).status,404);
 app.store.approve(p.id,v.id,v.sha256,app.store.get(p.id).revision);
 const template=app.store.addTemplate({name:'Approved source recipe',baseTemplateId:'kinetic',instructions:'Use the approved source as the visual and audio reference.',projectId:p.id,versionId:v.id});
 const visible=app.snapshot().templates.find(x=>x.id===template.id);
 assert.equal(new URL(visible.previewURL).pathname,'/media/preview-'+v.id);
 assert.equal(new URL(visible.posterURL).pathname,'/media/poster-'+v.id);
 assert.equal(app.snapshot().templates.find(x=>x.id==='kinetic').previewURL,null);
 const templateRange=await fetch(visible.previewURL,{headers:{Range:'bytes=0-99'}});
 assert.equal(templateRange.status,206);assert.equal((await templateRange.arrayBuffer()).byteLength,100);
 assert.equal(app.store.read().attempts.length,0);
});
